const assert = require('node:assert/strict');
const {stats,dashboard} = require('../js/member-stats.js');
const base={id:'a',number:1,date:'2026-08-12',session_id:'s1',session_title:'Séance test',session_url:'seance-test.html',participant_count:2,committee_score:78,rubric_id:'v1',cigar_score:6.7,duration_minutes:60,criteria:[{label:'Critère',score:78,max:100}],brand:'Marque',module:'Robusto',origin:null,reference_exact:null,aromas:['Bois','Bois','Terre'],pairing:'Eau',ash_max_cm:null,url:'fiche-test.html',full_title:'Fiche test',technique:{draw:null,relights:null,touchups:null},first:true};
const second={...base,id:'b',number:2,committee_score:82,cigar_score:null,duration_minutes:null,aromas:undefined};
const third={...base,id:'c',number:3,date:'2026-09-12',session_id:'s2',participant_count:1,committee_score:90,cigar_score:8,duration_minutes:0,ash_max_cm:0,technique:{relights:0,touchups:0}};
const result=stats([second,third,base]);
assert.equal(result.sessions.length,2,'Do not count two sheets as two sessions');
assert.equal(result.collective,1);
assert.equal(result.duration.length,2,'Null is missing; zero is a valid measurement');
assert.equal(result.durationMean,30);
assert.equal(result.cigar.length,2,'Missing cigar scores are excluded from the average');
assert.equal(result.cigarMean,7.35);
assert.equal(stats([base]).committeeMean,78);
let html=dashboard([base]);
assert(html.includes('Historique en cours de constitution'));
assert(!html.includes('<polyline'),'One observation must not pretend to be a trend');
assert(html.includes('0 référence(s) commerciale(s) exacte(s)'));
assert(html.includes('aucune donnée renseignée'));
assert(!html.includes('NaN'));
html=dashboard([base,second,third]);
assert(html.includes('<polyline'));
assert(html.includes('Record : 0 cm'),'Zero measurement remains a measurement');
const different=dashboard([base,{...third,rubric_id:'v2'}]);
assert(different.includes('moyennes sont séparées'));
assert(different.includes('aucune variation chiffrée'));
const hostile=dashboard([{...base,brand:'<img src=x onerror=alert(1)>',aromas:['<script>bad</script>']}]);
assert(!hostile.includes('<img src=x'));
assert(!hostile.includes('<script>bad'));
assert(dashboard([]).includes('Aucune fiche'));
console.log('Member statistics checks passed: missing values, zeros, session deduplication, rubric separation, one-point charts, escaping.');
